export function slugify(s){return s.normalize('NFKD').replace(/[–—]/g,'-').toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');}
export function unitUrl(u){return upesscRoot+'unit-'+u.number+'-'+slugify(u.title)+'/';}
export function sectionUrl(u,s){return unitUrl(u)+s.letter.toLowerCase()+'-'+slugify(s.title)+'/';}
export function noteUrl(u,s,n){return sectionUrl(u,s)+n.code.toLowerCase()+'-'+slugify(n.title)+'/';}
export function notesCount(u){return u.sections.reduce((n,s)=>n+s.notes.length,0);}
